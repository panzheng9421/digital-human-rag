    /** 从富化结果中提取 [画面提示] 段，作为 Seedance 的 prompt 字段 */
    public String extractVisual(String enriched) {
        String vis = extractVisualRaw(enriched);
        return capTimestamps(vis, videoSeconds);
    }

    /** 提取原始 [画面提示] 块（不做时间戳裁剪）。
     *  [画面提示] 现为本任务唯一输出块，已内嵌【音色锚定】（台词节奏信息内联进【事件脚本】），
     *  因此截取到字符串末尾；若模型误在末尾追加 [台词] 标记则在此之前停（防御，正常不会发生）。 */
    public static String extractVisualRaw(String enriched) {
        if (enriched == null) return "";
        // 全角→半角归一化：兼容 DeepSeek 输出括号形态漂移（【】vs []），否则锚点匹配失败会把噪音泄露给视频模型
        enriched = enriched.replace("【", "[").replace("】", "]");
        int start = enriched.indexOf("[画面提示]");
        if (start < 0) return enriched.trim();
        start = enriched.indexOf("\n", start);
        if (start < 0) start = 0;
        int end = enriched.indexOf("[台词]", start);
        if (end < 0) end = enriched.length();
        return enriched.substring(start, end).trim();
    }

    /** 时间戳正则：匹配 [Xs-Ys] 格式 */
    private static final Pattern TIMESTAMP_PATTERN = Pattern.compile("\\[(\\d+)s-(\\d+)s\\]");

    /**
     * 时间戳硬兜底：将所有超出 maxSeconds 的时间戳裁剪回合法范围。
     * 处理规则：
     *   1) [Xs-Ys] 中 Y > maxSeconds → Y 改为 maxSeconds
     *   2) [Xs-Ys] 中 X >= maxSeconds → 整行删除（超限片段）
     */
    public static String capTimestamps(String visual, int maxSeconds) {
        if (visual == null || visual.isBlank() || maxSeconds <= 0) return visual;

        // 规则1：截断结束时间超限的时间戳 [Xs-Ys] 其中 Y > maxSeconds → [Xs-{max}s]
        Matcher m = TIMESTAMP_PATTERN.matcher(visual);
        StringBuffer sb = new StringBuffer();
        while (m.find()) {
            int end = Integer.parseInt(m.group(2));
            if (end > maxSeconds) {
                m.appendReplacement(sb, "[" + m.group(1) + "-" + maxSeconds + "s]");
            } else {
                m.appendReplacement(sb, m.group(0));
            }
        }
        m.appendTail(sb);
        String result = sb.toString();

        // 规则2：删除起始时间已超限的整行（如 [35s-42s]...）
        result = result.replaceAll(
                "(?m)^\\s*\\[" + maxSeconds + "[^]]*s\\].*$",
                ""
        );

        // 规则3：清理可能的空行
        result = result.replaceAll("(?m)^\\s*\\n", "\n").trim();

        return result;
    }
